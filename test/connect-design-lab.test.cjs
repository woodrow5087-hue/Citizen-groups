'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {JSDOM}=require('jsdom');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'connect-design-lab.html'),'utf8');
const script=fs.readFileSync(path.join(root,'connect-design-lab.js'),'utf8');
function preview(){
  const dom=new JSDOM(html,{url:'https://example.test/connect-design-lab.html',runScripts:'outside-only',pretendToBeVisual:true});
  const {window}=dom;
  const dialog=window.document.querySelector('#new-dialog');
  dialog.showModal=function(){this.open=true;};
  dialog.close=function(){this.open=false;};
  window.HTMLElement.prototype.scrollIntoView=function(){};
  window.eval(script);
  const $=selector=>window.document.querySelector(selector);
  const click=selector=>$(selector).click();
  return {dom,window,$,click};
}
test('Connect visual lab is explicitly fictional and isolated from production',()=>{
  assert.match(html,/fictional/i);
  assert.match(html,/Nothing sends to another person/i);
  assert.doesNotMatch(script,/fetch\s*\(|XMLHttpRequest|WebSocket|supabase|localStorage|sessionStorage/);
  assert.match(fs.readFileSync(path.join(root,'scripts/build.cjs'),'utf8'),/'connect-design-lab.html'/);
});
test('Connect navigation opens readable chat and sends escaped local demo message',()=>{
  const app=preview();
  const {window,$,click}=app;
  assert.equal($('#screen-inbox').hidden,false);
  click('[data-open="thread"]');
  assert.equal($('#screen-inbox').hidden,true);
  assert.equal($('#screen-thread').hidden,false);
  const input=$('#thread-input');
  const send=$('#thread-form button[type=submit]');
  assert.equal(send.disabled,true);
  input.value='<img src=x onerror=alert(1)> hello!';
  input.dispatchEvent(new window.Event('input',{bubbles:true}));
  assert.equal(send.disabled,false);
  $('#thread-form').dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));
  const added=$('#thread-new-messages');
  assert.match(added.textContent,/hello!/);
  assert.equal(added.querySelector('img'),null);
  assert.equal(send.disabled,true);
  app.dom.window.close();
});
test('Group room tabs, local RSVP and prayer feedback work',()=>{
  const app=preview();
  const {$,click}=app;
  click('[data-open="room"]');
  assert.equal($('#screen-room').hidden,false);
  click('#rsvp-action');
  assert.equal($('#rsvp-action').getAttribute('aria-pressed'),'true');
  click('#tab-room-plans');
  assert.equal($('#room-panel-plans').hidden,false);
  assert.equal($('#room-panel-chat').hidden,true);
  assert.equal($('#room-form').hidden,true);
  click('[data-rsvp-mirror]');
  assert.equal($('#rsvp-action').getAttribute('aria-pressed'),'false');
  click('[data-open="inbox"]');
  click('[data-open="thread"]');
  click('#prayer-action');
  assert.equal($('#prayer-action').getAttribute('aria-pressed'),'true');
  click('#chat-reaction');
  assert.equal($('#chat-reaction-count').textContent,'6');
  app.dom.window.close();
});
test('Conversation search and private conversation routes work',()=>{
  const app=preview();
  const {window,$,click}=app;
  click('#search-toggle');
  assert.equal($('#search-wrap').hidden,false);
  const search=$('#conversation-search');
  search.value='Alex';
  search.dispatchEvent(new window.Event('input',{bubbles:true}));
  assert.equal($('#no-results').hidden,true);
  assert.equal($('#conversation-list [data-person="Alex Morgan"]').hidden,false);
  assert.equal($('#conversation-list [data-open="room"]').hidden,true);
  click('#compose-toggle');
  assert.equal($('#new-dialog').open,true);
  click('#new-dialog [data-person="Jess"]');
  assert.equal($('#new-dialog').open,false);
  assert.equal($('#screen-direct').hidden,false);
  assert.equal($('#direct-name').textContent,'Jess');
  app.dom.window.close();
});