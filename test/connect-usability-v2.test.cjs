const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const html=read('connect-design-lab.html');
function preview(coarse=false){
 const dom=new JSDOM(html,{url:'https://example.test/connect-design-lab.html',runScripts:'outside-only',pretendToBeVisual:true});
 const {window}=dom;
 window.matchMedia=()=>({matches:coarse,addListener(){},removeListener(){}});
 const dialog=window.document.querySelector('#new-dialog');
 dialog.showModal=function(){this.open=true};
 dialog.close=function(){this.open=false};
 window.HTMLElement.prototype.scrollIntoView=function(){};
 window.eval(read('connect-design-lab.js'));
 window.eval(read('connect-alive.js'));
 const $=q=>window.document.querySelector(q);
 return {dom,window,$,click:q=>$(q).click()};
}
