// Introspect the disposable test database; emits no credentials or user data.
// Supabase CLI type generation remains an option on a full local/hosted stack.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
const query = `select json_build_object('columns',(select json_agg(c order by table_name,ordinal_position) from (select table_name,column_name,udt_name,is_nullable,column_default,ordinal_position from information_schema.columns where table_schema='public') c),'enums',(select json_object_agg(typname,labels) from (select t.typname,json_agg(e.enumlabel order by e.enumsortorder) labels from pg_type t join pg_namespace n on n.oid=t.typnamespace join pg_enum e on e.enumtypid=t.oid where n.nspname='public' group by t.typname) e),'functions',(select json_agg(json_build_object('name',p.proname,'names',p.proargnames,'types',(select json_agg(format_type(t,null)) from unnest(p.proargtypes::oid[]) t),'defaults',p.pronargdefaults,'returns',format_type(p.prorettype,null))) from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public'))::text;`;
const info = JSON.parse(
  execFileSync(
    "docker",
    ["exec", "cg-v06-db", "psql", "-U", "postgres", "-At", "-c", query],
    { encoding: "utf8" },
  ),
);
const type = (t) =>
  ["bool", "boolean"].includes(t)
    ? "boolean"
    : ["int4", "integer"].includes(t)
      ? "number"
      : info.enums[t]
        ? `Database['public']['Enums']['${t}']`
        : "string";
const names = [...new Set(info.columns.map((c) => c.table_name))];
let out =
  "// Generated by scripts/generate-beta-types.mjs from the migration-backed local database.\nexport type Database = { public: { Tables: {\n";
for (const name of names) {
  const columns = info.columns.filter((c) => c.table_name === name);
  out += `${JSON.stringify(name)}: {\n`;
  for (const shape of ["Row", "Insert", "Update"]) {
    out += `${shape}: {\n`;
    for (const c of columns) {
      const optional =
        shape === "Update" ||
        (shape === "Insert" &&
          (c.column_default !== null || c.is_nullable === "YES"));
      out += `${JSON.stringify(c.column_name)}${optional ? "?" : ""}: ${type(c.udt_name)}${c.is_nullable === "YES" ? " | null" : ""};\n`;
    }
    out += "};\n";
  }
  out += "Relationships: [];\n};\n";
}
out += "}; Views: { [_ in never]: never }; Functions: {\n";
for (const f of info.functions ?? []) {
  out += `${JSON.stringify(f.name)}: { Args: {`;
  for (let i = 0; i < (f.names ?? []).length; i++)
    out += `${f.names[i]}${i >= f.names.length - f.defaults ? "?" : ""}: ${type(f.types[i])};`;
  out += `}; Returns: ${f.returns === "void" ? "undefined" : type(f.returns)} };\n`;
}
out += "}; Enums: {\n";
for (const [name, labels] of Object.entries(info.enums))
  out += `${name}: ${labels.map(JSON.stringify).join(" | ")};\n`;
out += "}; CompositeTypes: { [_ in never]: never } } };\n";
writeFileSync("src/features/beta/database.types.ts", out);
console.log("Generated beta types from schema metadata only.");
